/** Drafts show in `next dev` only, never in production builds. */
const isVisible = (a: Article) => !a.draft || process.env.NODE_ENV !== "production";

export const visibleArticles = () => ARTICLES.filter(isVisible);

export const getArticle = (slug: string) =>
  visibleArticles().find((a) => a.slug === slug);

/** Rough reading time for Hebrew text (~200 words/min). */
export const readingMinutes = (a: Article) => {
  const words = a.blocks
    .flatMap((b) => ("ul" in b ? b.ul : [Object.values(b)[0] as string]))
    .join(" ")
    .split(/\s+/).length;
  return Math.max(1, Math.round(words / 200));
};
